export function resolveProviderBrandIconColor(brand: ProviderBrand, variant: ProviderBrandIconVariant = 'brand'): string {
  if (variant === 'onDark') return DARK_ICON_COLORS[brand]
  if (variant === 'onLight') return LIGHT_ICON_COLORS[brand]
  return BRAND_COLORS[brand]
}

export function resolveProviderBrand(provider: AIProvider | undefined, model: string): ProviderBrand {
  switch (inferModelFamily(provider, model)) {
    case 'gpt':
    case 'gpt-oss':
      return 'openai'
    case 'claude':
      return 'anthropic'
    case 'grok':
      return 'grok'
    case 'deepseek':
      return 'deepseek'
    case 'gemini':
    case 'gemma':
      return 'gemini'
    case 'qwen':
      return 'qwen'
    case 'mistral':
      return 'mistral'
    case 'llama':
      return 'meta'
    case 'glm':
      return 'zhipu'
    case 'kimi':
      return 'moonshot'
    case 'minimax':
      return 'minimax'
    default:
      return 'generic'
  }
}

