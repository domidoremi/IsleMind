/**
 * Small platform-neutral SHA-256 implementation used for context identity.
 *
 * Context planning is intentionally synchronous (it runs on the request
 * preparation path) and React Native does not expose Node's `crypto` module.
 * Keeping the digest here avoids a platform-specific dependency while giving
 * us a collision-resistant, auditable identity for fragments and artifacts.
 */

